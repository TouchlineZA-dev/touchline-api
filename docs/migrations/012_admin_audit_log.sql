-- 012 (touchline-sync V044): audit log for privileged operations (API Sprint 7).
--
-- Why: 03-Leruo-API Stage 7 / handbook Gate 9: "keep actor, timestamp, reason and outcome for
-- consequential operations" (scoring, pricing, calendar, corrections, admin resets, suspensions).
-- What: app.admin_audit_log, insert-only. The API writes one row per admin route call, including
-- refused ones (outcome 403).
-- Safe to rerun.

CREATE TABLE IF NOT EXISTS app.admin_audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id   INTEGER     REFERENCES app.users (id),
    action          TEXT        NOT NULL,          -- e.g. "POST api/v1/admin/gameweeks/{id:int}/score"
    target          JSONB       NOT NULL,          -- the route and simple arguments (ids, flags)
    reason          TEXT,                          -- from the request body when it has one
    outcome_status  INTEGER     NOT NULL,          -- HTTP status returned
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_admin_audit_log_created ON app.admin_audit_log (created_at DESC);

GRANT SELECT, INSERT ON app.admin_audit_log TO app_api_user;
ALTER TABLE app.admin_audit_log ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'app' AND tablename = 'admin_audit_log' AND policyname = 'api_full_access') THEN
        CREATE POLICY api_full_access ON app.admin_audit_log FOR ALL TO app_api_user USING (true) WITH CHECK (true);
    END IF;
END $$;
