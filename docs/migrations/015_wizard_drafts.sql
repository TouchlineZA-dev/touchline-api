-- 015 (touchline-sync V051): wizard drafts (API audit, 25 Nov 2026).
--
-- Why: wherever a manager gives input step by step (onboarding, picking a squad, changing the lineup,
-- planning transfers, creating or joining a league), the app saves unfinished work so it can offer
-- "Resume where you left off?" on any device. A draft is never a confirmed squad or entry and is
-- never scored: it lives only here, apart from every fantasy table.
-- What: app.wizard_drafts, one row per manager and kind.
--   - Saving overwrites the payload and bumps version; the app sends the version it last loaded, so a
--     stale save from a second device gets 409 instead of silently overwriting (the API checks it).
--   - Clearing sets cleared_at (an UPDATE). There is no DELETE grant.
--   - expires_at is set by the API from its Drafts:ExpiryDays setting; an expired draft is ignored.
-- Numbering: 013 and 014 are deliberately unused here. From 007 on, file NNN is V(NNN+36), and V049
-- (the sync owner's operations, renamed from V042) and V050 (api_handoff_fixes) already exist in
-- touchline-sync. V051 is the next free version on any branch.
-- Safe to rerun.

CREATE TABLE IF NOT EXISTS app.wizard_drafts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER     NOT NULL REFERENCES app.users (id),
    kind        TEXT        NOT NULL CHECK (kind IN ('onboarding', 'squad', 'lineup', 'transfers', 'league')),
    step        TEXT        CHECK (step IS NULL OR length(step) BETWEEN 1 AND 50),
    payload     JSONB       NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(payload) = 'object'),
    version     INTEGER     NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at  TIMESTAMPTZ NOT NULL,
    cleared_at  TIMESTAMPTZ,
    CONSTRAINT uq_wizard_drafts_user_kind UNIQUE (user_id, kind)
);

GRANT SELECT, INSERT, UPDATE ON app.wizard_drafts TO app_api_user;
ALTER TABLE app.wizard_drafts ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'app' AND tablename = 'wizard_drafts' AND policyname = 'api_full_access') THEN
        CREATE POLICY api_full_access ON app.wizard_drafts FOR ALL TO app_api_user USING (true) WITH CHECK (true);
    END IF;
END $$;

COMMENT ON TABLE app.wizard_drafts IS
    'Unfinished wizard input per manager and kind (API). Never a confirmed squad or entry; never scored. Cleared by UPDATE (cleared_at), never deleted.';
