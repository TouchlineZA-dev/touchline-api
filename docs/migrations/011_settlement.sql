-- 011 (touchline-sync V047): settlement, revisions and corrections (API Sprint 5).
--
-- Why: 03-Leruo-API Stage 5 / handbook Gate 7. A settled week must be rebuildable and explainable
-- from durable records: a state machine with reasons, an explicit per-fixture completeness outcome
-- (the worker's sync.gameweek_sync_status has 0 rows in production, so an admin's recorded manual
-- resolution is the other way to settle), and provisional / final / amendment score revisions that
-- are built in batches and published atomically.
--
-- What (all insert-only except the current-state row and a revision's status):
--   1. app.gameweek_settlement: the current state of each gameweek (open, locked, live,
--      awaiting_review, final) and its published revision.
--   2. app.gameweek_state_transitions: every transition with reason, input revision, actor and time.
--   3. app.fixture_resolutions: an admin's recorded outcome for a fixture the worker hasn't evidenced
--      (verified_zero, manual_resolution, unattributed_resolved), newest row wins.
--   4. app.score_revisions: one row per scoring run: kind (provisional, final, amendment), status
--      (building, published, abandoned), the input revision it was computed from, the revision it
--      replaces, and for amendments the source, reason, author and a correction message.
--   5. app.score_revision_teams: each team's total and full breakdown in a revision. A run writes
--      these in batches while "building"; publishing copies them into fantasy_gameweek_entries and
--      points_results in one transaction, so an interrupted run resumes without double counting.
--   6. Grants (SELECT, INSERT, UPDATE on the state and revision tables; never DELETE) and RLS policies.
--
-- Safe to rerun: IF NOT EXISTS everywhere.

CREATE TABLE IF NOT EXISTS app.gameweek_settlement (
    gameweek_id          INTEGER     PRIMARY KEY REFERENCES app.gameweeks (id),
    state                VARCHAR(20) NOT NULL CHECK (state IN ('open', 'locked', 'live', 'awaiting_review', 'final')),
    reason               TEXT        NOT NULL,
    input_revision       VARCHAR(40),
    published_revision_id INTEGER,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.gameweek_state_transitions (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gameweek_id      INTEGER     NOT NULL REFERENCES app.gameweeks (id),
    from_state       VARCHAR(20),
    to_state         VARCHAR(20) NOT NULL,
    reason           TEXT        NOT NULL,
    input_revision   VARCHAR(40),
    actor_user_id    INTEGER     REFERENCES app.users (id),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_gameweek_state_transitions_gw ON app.gameweek_state_transitions (gameweek_id, id);

CREATE TABLE IF NOT EXISTS app.fixture_resolutions (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixture_id       INTEGER     NOT NULL,          -- football.fixtures.id (no FK: the worker owns football rows)
    outcome          VARCHAR(30) NOT NULL CHECK (outcome IN ('verified_zero', 'manual_resolution', 'unattributed_resolved')),
    reason           TEXT        NOT NULL,
    fixture_revision VARCHAR(40) NOT NULL,          -- the match facts the decision was made on
    actor_user_id    INTEGER     NOT NULL REFERENCES app.users (id),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fixture_resolutions_fixture ON app.fixture_resolutions (fixture_id, id DESC);

CREATE TABLE IF NOT EXISTS app.score_revisions (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gameweek_id            INTEGER     NOT NULL REFERENCES app.gameweeks (id),
    kind                   VARCHAR(20) NOT NULL CHECK (kind IN ('provisional', 'final', 'amendment')),
    status                 VARCHAR(20) NOT NULL CHECK (status IN ('building', 'published', 'abandoned')),
    input_revision         VARCHAR(40) NOT NULL,
    previous_revision_id   INTEGER     REFERENCES app.score_revisions (id),
    rules_version          VARCHAR(30) NOT NULL,
    source                 TEXT,
    reason                 TEXT,
    correction_message     TEXT,
    author_user_id         INTEGER     REFERENCES app.users (id),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at           TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_score_revisions_gw ON app.score_revisions (gameweek_id, id DESC);

CREATE TABLE IF NOT EXISTS app.score_revision_teams (
    revision_id        INTEGER     NOT NULL REFERENCES app.score_revisions (id),
    fantasy_team_id    INTEGER     NOT NULL REFERENCES app.fantasy_teams (id),
    total              INTEGER     NOT NULL,
    points_before_hits INTEGER     NOT NULL,
    bench_points       INTEGER     NOT NULL,
    transfer_cost      INTEGER     NOT NULL,
    breakdown          JSONB       NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (revision_id, fantasy_team_id)
);

GRANT SELECT, INSERT, UPDATE ON app.gameweek_settlement, app.score_revisions TO app_api_user;
GRANT SELECT, INSERT ON app.gameweek_state_transitions, app.fixture_resolutions, app.score_revision_teams TO app_api_user;

DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['gameweek_settlement', 'gameweek_state_transitions', 'fixture_resolutions', 'score_revisions', 'score_revision_teams'] LOOP
        EXECUTE format('ALTER TABLE app.%I ENABLE ROW LEVEL SECURITY', t);
        IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'app' AND tablename = t AND policyname = 'api_full_access') THEN
            EXECUTE format('CREATE POLICY api_full_access ON app.%I FOR ALL TO app_api_user USING (true) WITH CHECK (true)', t);
        END IF;
    END LOOP;
END $$;
