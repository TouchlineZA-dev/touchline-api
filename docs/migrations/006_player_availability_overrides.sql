-- 006: admin overrides for which players can be picked.
--
-- What:       app.player_availability_overrides. A player is pickable and priced when he has been in a
--             PSL matchday squad (lineup type 11 or 12) in the season; an admin can override that per
--             season through PUT /api/v1/admin/players/{id}/available, e.g. for a new signing who hasn't
--             made a squad yet, or a player who has left. Insert only: the latest row per player and
--             season wins. Every override needs a reason.
-- Depends on: 003 (the app.users rows admins sign in as).
-- How:        applied by hand in the Supabase SQL Editor by an owner account (postgres), after 005.
--             Until it runs the API still works; it just applies no overrides.
-- Re-running: safe. The table, index and policy are only created if missing; grants can repeat.
--
-- Same pattern as 005: row-level security is on, with a policy for app_api_user only.

CREATE TABLE IF NOT EXISTS app.player_availability_overrides (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id           INTEGER     NOT NULL REFERENCES football.players (id),
    season_id           INTEGER     NOT NULL REFERENCES football.seasons (id),
    is_available        BOOLEAN     NOT NULL,
    reason              TEXT        NOT NULL CHECK (length(trim(reason)) > 0),
    created_by_user_id  INTEGER     NOT NULL REFERENCES app.users (id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_player_availability_overrides_player_season
    ON app.player_availability_overrides (player_id, season_id, created_at DESC);

GRANT SELECT, INSERT ON app.player_availability_overrides TO app_api_user;
GRANT USAGE, SELECT ON SEQUENCE app.player_availability_overrides_id_seq TO app_api_user;

ALTER TABLE app.player_availability_overrides ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies
                   WHERE schemaname = 'app' AND tablename = 'player_availability_overrides' AND policyname = 'api_full_access') THEN
        CREATE POLICY api_full_access ON app.player_availability_overrides
            FOR ALL TO app_api_user USING (true) WITH CHECK (true);
    END IF;
END $$;
