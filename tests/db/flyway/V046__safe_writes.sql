-- V046: mirrored from touchline-api docs/migrations/010_safe_writes.sql (keep the two identical).
-- 010 (touchline-sync V046): deadline-safe writes (API Sprint 4).
--
-- Why: 03-Leruo-API Stage 4 / handbook Gate 6. Every accepted manager action needs exactly one
-- receipt, a retried request must return its original result, the transfer allowance must be
-- auditable per gameweek, and the entry a team takes into a gameweek must be frozen at the deadline.
--
-- What:
--   1. app.fantasy_receipts: one row per accepted action (transfer confirmation first). An optional
--      Idempotency-Key is unique per user and operation, bound to a SHA-256 hash of the request, so a
--      retry with the same key and body returns the stored result and a different body is refused.
--      Insert-only.
--   2. app.fantasy_gameweek_entries:
--        free_transfers_granted  the free transfers the gameweek allowed (NULL = unlimited)
--        locked_at, locked_snapshot  the immutable entry at the deadline (XI, bench order, captain,
--                                    vice, chip, purchase prices, transfers and cost), written once
--   3. app.fantasy_chip_usage.cancelled_at: a cancelled chip (allowed before the deadline for Bench
--      Boost and Triple Captain) is kept and marked, never deleted.
--   4. Grants (SELECT, INSERT on receipts; never DELETE) and an RLS policy for app_api_user.
--
-- Safe to rerun: IF NOT EXISTS everywhere.

CREATE TABLE IF NOT EXISTS app.fantasy_receipts (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fantasy_team_id   INTEGER      NOT NULL REFERENCES app.fantasy_teams (id),
    user_id           INTEGER      NOT NULL REFERENCES app.users (id),
    gameweek_id       INTEGER      NOT NULL REFERENCES app.gameweeks (id),
    operation         VARCHAR(30)  NOT NULL,
    idempotency_key   VARCHAR(100),
    payload_hash      CHAR(64),
    squad_version     INTEGER      NOT NULL,
    result            JSONB        NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_fantasy_receipts_idempotency
    ON app.fantasy_receipts (user_id, operation, idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_fantasy_receipts_team_gw ON app.fantasy_receipts (fantasy_team_id, gameweek_id);
COMMENT ON TABLE app.fantasy_receipts IS
    'Insert-only. One row per accepted manager action; the Idempotency-Key makes retries return the stored result.';

ALTER TABLE app.fantasy_gameweek_entries ADD COLUMN IF NOT EXISTS free_transfers_granted INTEGER;
ALTER TABLE app.fantasy_gameweek_entries ADD COLUMN IF NOT EXISTS locked_at       TIMESTAMPTZ;
ALTER TABLE app.fantasy_gameweek_entries ADD COLUMN IF NOT EXISTS locked_snapshot JSONB;
COMMENT ON COLUMN app.fantasy_gameweek_entries.locked_snapshot IS
    'The entry as it stood at the deadline. Written once, never changed.';

ALTER TABLE app.fantasy_chip_usage ADD COLUMN IF NOT EXISTS cancelled_at TIMESTAMPTZ;

GRANT SELECT, INSERT ON app.fantasy_receipts TO app_api_user;
ALTER TABLE app.fantasy_receipts ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'app' AND tablename = 'fantasy_receipts' AND policyname = 'api_full_access') THEN
        CREATE POLICY api_full_access ON app.fantasy_receipts FOR ALL TO app_api_user USING (true) WITH CHECK (true);
    END IF;
END $$;
